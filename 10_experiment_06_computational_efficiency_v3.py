"""
10_experiment_06_computational_efficiency.py

Experiment 6: Computational Efficiency and Scalability
Digital Forensic Evidence Synthesis Framework

Purpose
-------
Measure the actual computational requirements of the implemented multi-view
forensic evidence synthesis framework.

The experiment DOES NOT retrain the predictive models. It reuses:
- the exact view-level pipelines saved by Experiment 3;
- their recorded historical training times;
- the finalized A7 Full FERF weights and threshold from Experiment 4;
- the fixed Experiment 2.1 split assignments;
- the saved record-view reliability components.

Measured outputs
----------------
1. Historical model training time:
   Sum of the actual per-view training_seconds stored by the completed
   multi-view experiment.

2. Standardized inference benchmark:
   Reload the exact saved view pipelines and run predict_proba over the same
   held-out records used previously.

3. FERF arithmetic overhead:
   Measure reliability combination + weighted fusion + thresholding using the
   finalized A7 Full FERF configuration from Experiment 4.

4. End-to-end analytical inference:
   View-model inference + FERF arithmetic.

5. Memory:
   Process resident-set-size (RSS) baseline and peak RSS during the measured
   benchmark. This captures Python plus native-library allocations visible to
   the operating system and is preferable to tracemalloc for XGBoost.

6. Model storage:
   Sum serialized saved view-model file sizes.

7. Scalability:
   Repeat inference at increasing record counts and report wall-clock time,
   latency, throughput, and peak RSS.

Important scope
---------------
The benchmark measures the implemented analytical reasoning path beginning
with already prepared network-flow attributes. Disk loading, dataset cleaning,
acquisition hashing, and initial data preparation are NOT included in the
per-record inference time.

Reliability component values (integrity, information quality, temporal
reliability) were already generated by the completed multi-view experiment.
Experiment 6 measures the runtime required to combine these components and
perform FERF; it does not refit the information-quality estimator.

Run
---
python 10_experiment_06_computational_efficiency.py --dataset all

Optional
--------
python 10_experiment_06_computational_efficiency.py --dataset CICIDS2017
python 10_experiment_06_computational_efficiency.py --dataset all --repeats 5
"""

