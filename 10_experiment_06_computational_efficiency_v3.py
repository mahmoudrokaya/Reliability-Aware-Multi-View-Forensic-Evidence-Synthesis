def load_existing_configuration(
    dataset: str,
) -> tuple[
    list[str],
    dict[str, list[str]],
    np.ndarray,
    float,
]:
    """
    Load:
    - the semantic-view mapping from Experiment 3;
    - the finalized A7 Full FERF threshold and weights from
      Experiment 4 Metrics/ablation_results.csv.
    """

    design_path = (
        MULTIVIEW_ROOT
        / dataset
        / "Manifests"
        / "design.json"
    )

    ablation_path = (
        get_ablation_results_path(
            dataset
        )
    )

    design = load_json(
        design_path
    )

    views_mapping = {
        str(key): list(value)
        for key, value
        in design[
            "views"
        ].items()
    }

    ablation = pd.read_csv(
        ablation_path
    )

    required_columns = {
        "configuration",
        "threshold",
        "weights_json",
    }

    missing_columns = (
        required_columns
        - set(
            ablation.columns
        )
    )

    if missing_columns:
        raise ValueError(
            f"{dataset}: ablation_results.csv is missing "
            f"required columns: {sorted(missing_columns)}"
        )

    full_rows = ablation.loc[
        ablation[
            "configuration"
        ].astype(str).eq(
            "A7_Full_FERF"
        )
    ]

    if full_rows.empty:
        raise ValueError(
            f"{dataset}: A7_Full_FERF was not found in "
            f"{ablation_path}"
        )

    full_ferf = full_rows.iloc[
        -1
    ]

    try:
        weights_dict = json.loads(
            str(
                full_ferf[
                    "weights_json"
                ]
            )
        )
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"{dataset}: could not parse weights_json in "
            f"{ablation_path}"
        ) from exc

    if not isinstance(
        weights_dict,
        dict,
    ) or not weights_dict:
        raise ValueError(
            f"{dataset}: Full FERF weights are missing or invalid."
        )

    # Use the Experiment 4 view order when available because that is
    # the exact order used by the A7 configuration. Fall back to the
    # Experiment 3 design order if needed.
    manifest_path = (
        get_ablation_manifest_path(
            dataset
        )
    )

    experiment4_views = []

    if manifest_path.exists():
        manifest = load_json(
            manifest_path
        )

        experiment4_views = [
            str(view)
            for view in manifest.get(
                "views",
                []
            )
        ]

    if experiment4_views:
        views = [
            view
            for view in experiment4_views
            if (
                view in views_mapping
                and view in weights_dict
            )
        ]
    else:
        views = [
            view
            for view in views_mapping.keys()
            if view in weights_dict
        ]

    if not views:
        raise ValueError(
            f"{dataset}: no valid semantic views overlap between "
            "Experiment 3 design and Experiment 4 A7 weights."
        )

    missing_weights = [
        view
        for view in views
        if view not in weights_dict
    ]

    if missing_weights:
        raise ValueError(
            f"{dataset}: missing Full FERF weights for views: "
            f"{missing_weights}"
        )

    weights = np.array(
        [
            float(
                weights_dict[
                    view
                ]
            )
            for view in views
        ],
        dtype=float,
    )

    threshold = float(
        full_ferf[
            "threshold"
        ]
    )

    if not np.isfinite(
        weights
    ).all():
        raise ValueError(
            f"{dataset}: non-finite FERF weights detected."
        )

    weight_sum = float(
        weights.sum()
    )

    if weight_sum <= 0:
        raise ValueError(
            f"{dataset}: FERF weights sum to zero."
        )

    weights = (
        weights
        / weight_sum
    )

    LOGGER.info(
        "%s | Full FERF configuration source: %s",
        dataset,
        ablation_path,
    )

    LOGGER.info(
        "%s | Full FERF threshold=%.3f | weights=%s",
        dataset,
        threshold,
        {
            view: round(
                float(
                    weights[index]
                ),
                6,
            )
            for index, view
            in enumerate(
                views
            )
        },
    )

    return (
        views,
        views_mapping,
        weights,
        threshold,
    )


def load_models(
    dataset: str,
    views: list[str],
) -> dict[str, Any]:
    models = {}

    for view in views:
        candidates = [
            MULTIVIEW_ROOT
            / dataset
            / "Models"
            / f"{view}_pipeline.pkl",
            MULTIVIEW_ROOT
            / dataset
            / "Models"
            / f"{view}.pkl",
        ]

        path = next(
            (
                candidate
                for candidate
                in candidates
                if candidate.exists()
            ),
            None,
        )

        if path is None:
            raise FileNotFoundError(
                f"No saved model was found for "
                f"{dataset}/{view}."
            )

        with path.open("rb") as stream:
            models[view] = pickle.load(
                stream
            )

    return models


