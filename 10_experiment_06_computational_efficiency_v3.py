def build_reliability(
    frame: pd.DataFrame,
    views: list[str],
) -> np.ndarray:
    columns = []

    for view in views:
        integrity = pd.to_numeric(
            frame[f"{view}__integrity"],
            errors="coerce",
        ).fillna(0.5).to_numpy(
            dtype=float
        )

        quality = pd.to_numeric(
            frame[f"{view}__quality"],
            errors="coerce",
        ).fillna(0.5).to_numpy(
            dtype=float
        )

        temporal = pd.to_numeric(
            frame[f"{view}__temporal"],
            errors="coerce",
        ).fillna(0.5).to_numpy(
            dtype=float
        )

        reliability = (
            INTEGRITY_WEIGHT
            * integrity
            + QUALITY_WEIGHT
            * quality
            + TEMPORAL_WEIGHT
            * temporal
        )

        columns.append(
            np.clip(
                reliability,
                0.0,
                1.0,
            )
        )

    return np.column_stack(
        columns
    )


def fuse_probabilities(
    probabilities: np.ndarray,
    reliabilities: np.ndarray,
    weights: np.ndarray,
) -> np.ndarray:
    weighted_reliability = (
        reliabilities
        * weights.reshape(
            1,
            -1,
        )
    )

    denominator = np.maximum(
        weighted_reliability.sum(
            axis=1
        ),
        EPSILON,
    )

    return (
        weighted_reliability
        * probabilities
    ).sum(
        axis=1
    ) / denominator


