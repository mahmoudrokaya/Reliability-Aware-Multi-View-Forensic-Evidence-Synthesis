def discover_parts(dataset: str) -> list[Path]:
    cleaned_dir = (
        CLEANING_ROOT
        / dataset
        / "Cleaned_Data"
    )

    parquet = sorted(
        cleaned_dir.glob(
            "cleaned_part_*.parquet"
        )
    )

    if parquet:
        return parquet

    return sorted(
        cleaned_dir.glob(
            "cleaned_part_*.csv.gz"
        )
    )


def read_part(path: Path) -> pd.DataFrame:
    if path.suffix.lower() == ".parquet":
        return pd.read_parquet(path)

    return pd.read_csv(
        path,
        compression="gzip",
        low_memory=False,
    )


def count_rows(path: Path) -> int:
    if path.suffix.lower() == ".parquet":
        import pyarrow.parquet as pq

        return int(
            pq.ParquetFile(
                path
            ).metadata.num_rows
        )

    total = 0

    for chunk in pd.read_csv(
        path,
        compression="gzip",
        usecols=[0],
        chunksize=250_000,
    ):
        total += len(chunk)

    return total


def allocate_rows(
    sizes: list[int],
    target: int,
) -> list[int]:
    total = sum(sizes)

    if target <= 0 or target >= total:
        return sizes.copy()

    exact = [
        target * size / total
        for size in sizes
    ]

    allocation = [
        min(
            size,
            int(np.floor(value)),
        )
        for size, value
        in zip(sizes, exact)
    ]

    remainder = (
        target
        - sum(allocation)
    )

    order = np.argsort(
        [
            value - np.floor(value)
            for value in exact
        ]
    )[::-1]

    for index in order:
        if remainder <= 0:
            break

        if allocation[index] < sizes[index]:
            allocation[index] += 1
            remainder -= 1

    return allocation


def load_sample(
    dataset: str,
    maximum_rows: int,
    seed: int,
) -> tuple[pd.DataFrame, int]:
    parts = discover_parts(dataset)

    if not parts:
        raise FileNotFoundError(
            f"No cleaned parts found for {dataset}."
        )

    LOGGER.info(
        "%s | counting %d cleaned parts...",
        dataset,
        len(parts),
    )

    sizes = [
        count_rows(path)
        for path in parts
    ]

    total_available = sum(sizes)

    requested = (
        total_available
        if maximum_rows <= 0
        else min(
            maximum_rows,
            total_available,
        )
    )

    allocations = allocate_rows(
        sizes,
        requested,
    )

    frames = []

    for index, (
        path,
        part_size,
        selected,
    ) in enumerate(
        zip(
            parts,
            sizes,
            allocations,
        ),
        start=1,
    ):
        if selected <= 0:
            continue

        frame = read_part(path)

        if selected < part_size:
            frame = frame.sample(
                n=selected,
                random_state=(
                    seed + index
                ),
            )

        frames.append(frame)

        LOGGER.info(
            "%s | loaded part %d/%d | %d/%d rows",
            dataset,
            index,
            len(parts),
            len(frame),
            part_size,
        )

    dataframe = pd.concat(
        frames,
        ignore_index=True,
        sort=False,
    )

    if len(dataframe) > requested:
        dataframe = dataframe.sample(
            n=requested,
            random_state=seed,
        ).reset_index(drop=True)

    return dataframe, total_available


def select_predictors(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    if "binary_label" not in dataframe.columns:
        raise ValueError(
            "binary_label is missing."
        )

    target = pd.to_numeric(
        dataframe["binary_label"],
        errors="coerce",
    )

    valid = target.isin([0, 1])

    dataframe = dataframe.loc[
        valid
    ].copy()

    excluded = set(
        NON_PREDICTIVE_COLUMNS
    )

    for column in dataframe.columns:
        if is_identifier_column(column):
            excluded.add(column)

    features = dataframe[
        [
            column
            for column in dataframe.columns
            if column not in excluded
        ]
    ].copy()

    all_missing = [
        column
        for column in features.columns
        if features[column].isna().all()
    ]

    constant = [
        column
        for column in features.columns
        if features[column].nunique(
            dropna=True
        ) <= 1
    ]

    features = features.drop(
        columns=sorted(
            set(all_missing)
            | set(constant)
        ),
        errors="ignore",
    )

    return features.reset_index(
        drop=True
    )


