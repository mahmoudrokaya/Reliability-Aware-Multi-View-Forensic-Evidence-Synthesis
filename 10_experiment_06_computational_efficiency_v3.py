def infer_view_models(
    models: dict[str, Any],
    views: list[str],
    views_mapping: dict[str, list[str]],
    X: pd.DataFrame,
) -> np.ndarray:
    probabilities = []

    for view in views:
        columns = views_mapping[
            view
        ]

        probability = (
            models[
                view
            ].predict_proba(
                X[
                    columns
                ]
            )[
                :,
                1,
            ]
        )

        probabilities.append(
            np.asarray(
                probability,
                dtype=float,
            )
        )

    return np.column_stack(
        probabilities
    )


