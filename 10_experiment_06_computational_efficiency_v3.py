def parse_scale_sizes(
    text: str,
) -> tuple[int, ...]:
    values = []

    for part in text.split(","):
        stripped = part.strip()

        if not stripped:
            continue

        value = int(
            stripped
        )

        if value <= 0:
            raise ValueError(
                "Scale sizes must be positive."
            )

        values.append(
            value
        )

    if not values:
        raise ValueError(
            "At least one scale size is required."
        )

    return tuple(
        sorted(
            set(
                values
            )
        )
    )


