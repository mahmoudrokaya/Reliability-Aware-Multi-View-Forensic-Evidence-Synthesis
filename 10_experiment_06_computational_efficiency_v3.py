def save_consolidated(
    summaries: list[
        EfficiencySummary
    ],
    scalability_frames: list[
        pd.DataFrame
    ],
) -> None:
    summary_frame = pd.DataFrame(
        [
            asdict(
                summary
            )
            for summary in summaries
        ]
    )

    summary_frame.to_csv(
        REPORTS_DIR
        / "Computational_Efficiency_Summary.csv",
        index=False,
    )

    if scalability_frames:
        scalability = pd.concat(
            scalability_frames,
            ignore_index=True,
        )

        scalability.to_csv(
            REPORTS_DIR
            / "Scalability_Summary.csv",
            index=False,
        )

        scaling_records = []

        for dataset, group in scalability.groupby(
            "dataset"
        ):
            group = group.sort_values(
                "rows"
            )

            x = group[
                "rows"
            ].to_numpy(
                dtype=float
            )

            y = group[
                "end_to_end_seconds_mean"
            ].to_numpy(
                dtype=float
            )

            if len(x) >= 2:
                slope, intercept = np.polyfit(
                    x,
                    y,
                    1,
                )

                predicted = (
                    slope * x
                    + intercept
                )

                ss_res = float(
                    np.sum(
                        (
                            y
                            - predicted
                        )
                        ** 2
                    )
                )

                ss_tot = float(
                    np.sum(
                        (
                            y
                            - y.mean()
                        )
                        ** 2
                    )
                )

                r_squared = (
                    1.0
                    - ss_res
                    / ss_tot
                    if ss_tot > 0
                    else float("nan")
                )

                scaling_records.append(
                    {
                        "dataset": dataset,
                        "slope_seconds_per_record": (
                            float(
                                slope
                            )
                        ),
                        "intercept_seconds": (
                            float(
                                intercept
                            )
                        ),
                        "linear_fit_r_squared": (
                            r_squared
                        ),
                        "minimum_rows": (
                            int(
                                x.min()
                            )
                        ),
                        "maximum_rows": (
                            int(
                                x.max()
                            )
                        ),
                    }
                )

        pd.DataFrame(
            scaling_records
        ).to_csv(
            REPORTS_DIR
            / "Scalability_Linear_Fit.csv",
            index=False,
        )


