from pathlib import Path
import csv
import json
from datetime import datetime

# ============================================================
# Root folder
# ============================================================

ROOT = Path(
    r"D:\47\472\New-Papers\Digital_Forensics_Framework_Network Intrusions"
    r"\Experiments\Results"
)

# Save outputs in the SAME folder
TREE_FILE = ROOT / "results_folder_tree.txt"
CSV_FILE = ROOT / "results_file_inventory.csv"
JSON_FILE = ROOT / "results_file_inventory.json"
SUMMARY_FILE = ROOT / "results_folder_summary.txt"


# ============================================================
# Containers
# ============================================================

tree_lines = []
inventory = []

folder_count = 0
file_count = 0
total_size = 0

# Files generated by this script should not be included
OUTPUT_FILES = {
    TREE_FILE.resolve(),
    CSV_FILE.resolve(),
    JSON_FILE.resolve(),
    SUMMARY_FILE.resolve(),
}


# ============================================================
# Recursive tree function
# ============================================================

def build_tree(directory: Path, prefix: str = ""):
    global folder_count, file_count, total_size

    try:
        items = sorted(
            directory.iterdir(),
            key=lambda x: (not x.is_dir(), x.name.lower())
        )
    except PermissionError:
        tree_lines.append(
            f"{prefix}[Permission denied: {directory}]"
        )
        return

    # Exclude this script's generated output files
    items = [
        item for item in items
        if item.resolve() not in OUTPUT_FILES
    ]

    for index, item in enumerate(items):
        is_last = index == len(items) - 1

        connector = "└── " if is_last else "├── "
        child_prefix = prefix + (
            "    " if is_last else "│   "
        )

        relative_path = item.relative_to(ROOT)

        # ----------------------------------------------------
        # Folder
        # ----------------------------------------------------

        if item.is_dir():
            folder_count += 1

            tree_lines.append(
                f"{prefix}{connector}📁 {item.name}/"
            )

            build_tree(
                item,
                child_prefix
            )

        # ----------------------------------------------------
        # File
        # ----------------------------------------------------

        elif item.is_file():
            file_count += 1

            try:
                size_bytes = item.stat().st_size
            except OSError:
                size_bytes = 0

            total_size += size_bytes

            tree_lines.append(
                f"{prefix}{connector}📄 {item.name}"
            )

            inventory.append(
                {
                    "relative_path": str(relative_path),
                    "parent_folder": str(relative_path.parent),
                    "filename": item.name,
                    "extension": item.suffix.lower(),
                    "size_bytes": size_bytes,
                    "size_kb": round(
                        size_bytes / 1024,
                        3
                    ),
                    "size_mb": round(
                        size_bytes / (1024 ** 2),
                        3
                    ),
                }
            )


# ============================================================
# Check folder
# ============================================================

if not ROOT.exists():
    raise FileNotFoundError(
        f"Results folder does not exist:\n{ROOT}"
    )

if not ROOT.is_dir():
    raise NotADirectoryError(
        f"Path is not a directory:\n{ROOT}"
    )


# ============================================================
# Generate tree
# ============================================================

tree_lines.append(f"📁 {ROOT.name}/")

build_tree(ROOT)

tree_text = "\n".join(tree_lines)


# ============================================================
# Save TXT tree
# ============================================================

TREE_FILE.write_text(
    tree_text,
    encoding="utf-8"
)


# ============================================================
# Save CSV inventory
# ============================================================

fieldnames = [
    "relative_path",
    "parent_folder",
    "filename",
    "extension",
    "size_bytes",
    "size_kb",
    "size_mb",
]

with CSV_FILE.open(
    "w",
    newline="",
    encoding="utf-8-sig"
) as f:

    writer = csv.DictWriter(
        f,
        fieldnames=fieldnames
    )

    writer.writeheader()

    if inventory:
        writer.writerows(inventory)


# ============================================================
# Save JSON inventory
# ============================================================

summary = {
    "generated": datetime.now().isoformat(),
    "root": str(ROOT),
    "folder_count": folder_count,
    "file_count": file_count,
    "total_size_bytes": total_size,
    "total_size_mb": round(
        total_size / (1024 ** 2),
        3
    ),
    "total_size_gb": round(
        total_size / (1024 ** 3),
        3
    ),
    "files": inventory,
}

with JSON_FILE.open(
    "w",
    encoding="utf-8"
) as f:

    json.dump(
        summary,
        f,
        indent=4,
        ensure_ascii=False
    )


# ============================================================
# Save summary
# ============================================================

summary_text = f"""
RESULTS FOLDER STRUCTURE SUMMARY
================================

Generated:
{summary["generated"]}

Root:
{ROOT}

Folders:
{folder_count:,}

Files:
{file_count:,}

Total size:
{summary["total_size_mb"]:,.3f} MB
{summary["total_size_gb"]:,.3f} GB

Generated files:
{TREE_FILE.name}
{CSV_FILE.name}
{JSON_FILE.name}
{SUMMARY_FILE.name}
""".strip()

SUMMARY_FILE.write_text(
    summary_text,
    encoding="utf-8"
)


